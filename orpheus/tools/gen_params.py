#!/usr/bin/env python3
"""ORPHEUS: writes Source/ParamDefs.inc from the parameter list in ui/src/synth.js (DEFS), so the plugin and the UI
always agree on every id, range, default and choice. Run after changing DEFS.

Left out: the guitar-only settings of SIREN in Obsidian (sensitivity, gate, chord, arpeggiator, guitar mix, ...) and
AETHER. The UI may still send them; the plugin ignores ids it doesn't know."""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(HERE, 'ui/src/synth.js'), encoding='utf-8').read()
m = re.search(r'const DEFS = (\[.*?\n\]);', src, re.S)
if not m: sys.exit('DEFS not found in synth.js')
defs = json.loads(subprocess.run(['node', '-e', 'console.log(JSON.stringify(' + m.group(1) + '))'], capture_output=True, text=True, check=True).stdout)

SKIP = re.compile(r'^(atm\.|syn\.(sens|gate|hold|chord|key|scale|mix|post|power|b\.sync|arp\.|env\.f\.(att|dec|sus)$))')
out = ['// Generated by tools/gen_params.py from ui/src/synth.js (DEFS). Do not edit by hand.',
       '// { id, type, min, max, default, skew, choices ("A|B|C") }   type: 0 float, 1 log, 2 int, 3 bool, 4 choice']
T = {'f': 0, 'log': 1, 'int': 2, 'bool': 3, 'choice': 4}
n = 0
for d in defs:
    pid, typ, lo, hi, df = d[0], d[1], d[2], d[3], d[4]
    if SKIP.match(pid): continue
    choices = d[5] if typ == 'choice' else ''
    skew = d[6] if typ == 'f' and len(d) > 6 else 1
    out.append('{ "%s", %d, %r, %r, %r, %r, "%s" },' % (pid, T[typ], float(lo), float(hi), float(df), float(skew), choices))
    n += 1
open(os.path.join(HERE, 'Source/ParamDefs.inc'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
# the same order as an enum, so the engine reads S[P_fx_rev_size] (ids with the "syn." cut and dots as underscores)
names = [d[0] for d in defs if not SKIP.match(d[0])]
enum = ['// Generated by tools/gen_params.py. Do not edit by hand.', 'enum PId : int {']
enum += ['    P_' + n[4:].replace('.', '_') + ',' for n in names] + ['    P_COUNT', '};']
open(os.path.join(HERE, 'Source/ParamIds.inc'), 'w', encoding='utf-8').write('\n'.join(enum) + '\n')
print(n, 'parameters')
