#!/usr/bin/env python3
"""ORPHEUS: writes Source/Seq/DefaultSong.inc, the song a new ORPHEUS starts with (the UI's own startVoices(), and its chord
marks), so the plugin plays the same song before its window has ever been opened. Run after changing the default song."""
import os, subprocess, json
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(HERE, 'ui/src/orpheus.js')).read()
a = src.index('/* ------------------------------------------------------------ constants */')
b = src.index('/* ------------------------------------------------------------ sound: SIREN plays the voices */')
js = 'const K = {}, dev = null, el = () => null;\n' + src[a:b] + '\ncalcMarks();\nprocess.stdout.write(JSON.stringify({ song: { V: st.V, bars: st.bars, sig: st.sig, grid: st.grid, ppb: st.ppb, bpm: st.bpm, loop: st.loop, showNotes: st.showNotes }, marks: marks.map(m => m.t) }));'
out = subprocess.run(['node', '-e', js], capture_output=True, text=True, check=True).stdout
d = json.loads(out)
song = json.dumps(d['song'], separators=(',', ':'))
marks = json.dumps(d['marks'], separators=(',', ':'))
p = os.path.join(HERE, 'Source/Seq/DefaultSong.inc')
open(p, 'w').write('// Generated by tools/gen_song.py from ui/src/orpheus.js. Do not edit by hand.\nstatic const char* kDefaultSong = R"ORPH(' + song + ')ORPH";\nstatic const char* kDefaultMarks = R"ORPH(' + marks + ')ORPH";\n')
print('ok', len(song), 'marks', len(d['marks']))
