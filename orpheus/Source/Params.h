#pragma once
/*  ORPHEUS · parameters
    Every SIREN setting the UI has (ui/src/synth.js DEFS) is a host parameter here, with the same id, range, default and
    choices (Source/ParamDefs.inc and ParamIds.inc are generated by tools/gen_params.py). Values are the real values the
    UI shows (Hz, %, ms, a choice's index), not 0..1.                                                                  */
#include <juce_audio_processors/juce_audio_processors.h>
#include <array>

namespace orph
{
#include "ParamIds.inc"

struct ParamDef { const char* id; int type; double lo, hi, def, skew; const char* choices; };
enum ParamType { PT_FLOAT = 0, PT_LOG = 1, PT_INT = 2, PT_BOOL = 3, PT_CHOICE = 4 };

const ParamDef* paramDefs();                     // P_COUNT entries, in PId order
int paramIndex (const juce::String& id);         // -1 if the plugin doesn't have it
juce::AudioProcessorValueTreeState::ParameterLayout makeLayout();

/** A copy of every parameter's real value, taken once per block: the engine reads S[P_xxx]. */
struct Snapshot
{
    std::array<float, P_COUNT> v {};
    float operator[] (int i) const noexcept { return v[(size_t) i]; }
    bool on (int i) const noexcept { return v[(size_t) i] > 0.5f; }
    int ch (int i) const noexcept { return (int) std::lround (v[(size_t) i]); }
};
} // namespace orph
